def repair_layout(project: Path, *, apply: bool = False) -> dict[str, Any]:
    """Inspect and replay journalled layout/model transactions (``.dado/.txn``).

    Recovery is report-first: without ``apply`` the report classifies every
    journal — ``building`` (a partial, never-replayable declaration:
    inspection/discard only), ``pending`` (replayable) and ``committed``.
    With ``apply=True`` only still-pending journals are replayed, through the
    trusted root set ``[.dado, .opencode]`` — a journal's own recorded roots
    are never authority. Building journals are never replayed, unreadable
    journals are reported rather than crashing the repair, and no replay
    happens without the transactions module (hard requirement).
    """
    project = Path(project).resolve()
    if FileTransaction is None:
        raise ConflictError("Durable transaction journal unavailable; repair requires the transactions module")
    trusted = [dado_dir(project), project / ".opencode"]
    txn_dir = dado_dir(project) / ".txn"
    journals: list[dict[str, Any]] = []
    replayed = 0
    for path in sorted(txn_dir.glob("*.json")) if txn_dir.is_dir() else []:
        try:
            raw = json.loads(path.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError) as exc:
            journals.append({"id": path.name, "phase": "unreadable",
                             "action": f"inspect manually: {exc}"})
            continue
        if not isinstance(raw, dict) or not isinstance(raw.get("ops"), list):
            journals.append({"id": path.name, "phase": "unreadable",
                             "action": "not a transaction journal; inspect manually"})
            continue
        entry = {
            "id": raw.get("id", path.name),
            "phase": raw.get("phase", "unknown"),
            "label": raw.get("label", ""),
            "ops": len(raw["ops"]),
        }
        if entry["phase"] == "building":
            entry["action"] = "inspection-only: partial declaration, never replayed (discard explicitly)"
        elif entry["phase"] == "pending":
            if not apply:
                entry["action"] = "replayable (pass apply=True)"
            else:
                try:
                    handle = FileTransaction.from_journal(path, roots=trusted)
                    result = handle.apply()
                    replayed += 1
                    entry["action"] = f"replayed (applied {result['applied']} ops)"
                except ValidationError as exc:
                    entry["action"] = f"refused: {exc}"
                except ConflictError as exc:
                    entry["action"] = f"conflict: {exc}"
        elif entry["phase"] == "committed":
            entry["action"] = "already applied; nothing to do"
        else:
            entry["action"] = f"unknown journal phase {entry['phase']!r}; inspect manually"
        journals.append(entry)
    return {
        "project": str(project),
        "trusted_roots": [str(root) for root in trusted],
        "apply": apply,
        "journals": journals,
        "replayed": replayed,
        "building": [entry["id"] for entry in journals if entry["phase"] == "building"],
        "note": "building journals are only for inspection; use seal (creator) or discard",
    }
