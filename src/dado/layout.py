"""Shared vs. local DADO layout: identity, config split and legacy migration.

This module implements ADR 0005 (phase 0). It is deliberately inert for
projects that have not been migrated or freshly initialized: every behavior
hinges on the presence of the versioned layout marker ``.dado/layout.yaml``
with ``version: 2`` ("layout2"). Without that marker all state continues to
live in the legacy single ``.dado/config.yaml`` exactly as before, so legacy
projects remain readable and editable until an explicit migration.

Physical layout (layout2)
=========================

=========================== ======== =========================================
Path                        Scope    Contents
=========================== ======== =========================================
``.dado/layout.yaml``       shared   ``version``, ``project_uuid``, ``created_at``
``.dado/config.yaml``       shared   policies only (approval, scheduler,
                                     verification, history, archive)
``.dado/config.local.yaml`` local    profiles + ``active_profile`` only
                                     (policy keys are rejected)
``.dado/identity``          local    ``checkout_uuid``, stable per clone
``.dado/work/``             physical ``active/``, ``archive/``, ``index.yaml``,
                                     ``events.jsonl`` — ignored individually;
                                     only explicit promotion of
                                     ``work/project/`` content is shared
``.dado/.gitignore``        shared   generated safely (append-only)
=========================== ======== =========================================

Local identity and UUIDs
========================
Identity is never path-derived: the shared ``project_uuid`` names the project
across clones, the ignored local ``checkout_uuid`` names the working copy, and
:func:`new_work_uuid` / :func:`new_execution_uuid` mint identities for work
and executions. Directory slugs stay human-friendly but never carry identity.

Git safety rules
================
- ``git ls-files`` is the truth for tracking; tracked operational files are
  always reported in diagnostics before any mutation.
- ``.dado/.gitignore`` is only ever extended (missing entries appended once);
  user lines and tracked files are never removed or rewritten to make them
  ignorable.
- Tracked ``.opencode`` agent files are never modified by layout2 tooling.
- Writes that mix shared and local state (migration, extraction) go through
  the ADR 0004 journal (:mod:`dado.transactions`) when it is importable,
  falling back to plain atomic writes otherwise.

No paid or remote APIs; everything is local files and the local ``git`` binary.
"""
from __future__ import annotations

import hashlib
import json
import subprocess
import time
import uuid
from pathlib import Path
from typing import Any

import yaml

from .errors import ConflictError, ValidationError
from .fs import atomic_write, file_lock, read_yaml

try:
    from .transactions import FileTransaction
except ImportError:  # pragma: no cover - journalless install is unsupported
    FileTransaction = None

LAYOUT_VERSION = 2
LAYOUT_DIR = ".dado"
LAYOUT_FILENAME = "layout.yaml"
SHARED_CONFIG_NAME = "config.yaml"
LOCAL_CONFIG_NAME = "config.local.yaml"
IDENTITY_NAME = "identity"
MANIFEST_NAME = "managed-files.json"
BACKUP_ROOT = "backups/layout-migration"

# Key set mirrored from src/dado/schemas/config.schema.json (schema unchanged in phase 0).
POLICY_KEYS = ("approval", "scheduler", "verification", "history", "archive")
PROFILE_KEYS = ("profiles", "active_profile")

GITIGNORE_HEADER = "# Generated by DADO layout (ADR 0005): local-only checkout state."
GITIGNORE_ENTRIES = (
    "config.local.yaml",
    "identity",
    "managed-files.json",
    "local/",
    "backups/",
    ".txn/",
    "*.lock",
    "work/active/",
    "work/archive/",
    "work/imports/",
    "work/events.jsonl",
    "work/index.yaml",
)

_TRACKED_LOCAL_TOP = frozenset({LOCAL_CONFIG_NAME, IDENTITY_NAME, MANIFEST_NAME, ".txn"})

# Work content that is explicitly shared when promoted via git.
SHARED_WORK_PREFIX = "work/project"

LOCK_TIMEOUT = 10.0  # seconds; tests may tighten for real serialization checks


def _ts() -> str:
    return time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())


def _stamp() -> str:
    return time.strftime("%Y%m%dT%H%M%SZ", time.gmtime())


def _sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


# ------------------------------------------------------------------ paths

def dado_dir(project: Path) -> Path:
    return Path(project) / LAYOUT_DIR


def layout_path(project: Path) -> Path:
    return dado_dir(project) / LAYOUT_FILENAME


def shared_config_path(project: Path) -> Path:
    return dado_dir(project) / SHARED_CONFIG_NAME


def local_config_path(project: Path) -> Path:
    return dado_dir(project) / LOCAL_CONFIG_NAME


def config_path_for_profiles(project: Path) -> Path:
    """Path of the file holding ``profiles``/``active_profile``.

    Layout2 projects keep profile state in the ignored ``config.local.yaml``;
    legacy projects (no layout marker) keep it in ``config.yaml``.
    """
    return local_config_path(project) if is_layout2(project) else shared_config_path(project)


def identity_path(project: Path) -> Path:
    return dado_dir(project) / IDENTITY_NAME


def gitignore_path(project: Path) -> Path:
    return dado_dir(project) / ".gitignore"


# ----------------------------------------------------------- layout marker

def read_layout(project: Path) -> dict[str, Any] | None:
    layout = read_yaml(layout_path(project))
    return layout if isinstance(layout, dict) else None


def is_layout2(project: Path) -> bool:
    """True only when the versioned layout marker selects version 2.

    A marker file that exists but does not parse, has an unknown version, or
    lacks a project UUID is an explicit error — layout state is never
    silently guessed as legacy.
    """
    path = layout_path(project)
    if not path.exists():
        return False
    marker = read_yaml(path)
    if not isinstance(marker, dict):
        raise ConflictError(
            f"Malformed {LAYOUT_FILENAME} at {path}: not a YAML mapping; "
            "layout state is never guessed. Fix or remove the marker explicitly."
        )
    version = marker.get("version")
    if not isinstance(version, int) or version != LAYOUT_VERSION:
        raise ConflictError(
            f"Unsupported layout marker version {version!r} in {path}; produced by a "
            "different DADO version. Review the file and resolve it explicitly."
        )
    uid = marker.get("project_uuid")
    if not isinstance(uid, str) or not uid:
        raise ConflictError(f"Malformed {LAYOUT_FILENAME} at {path}: missing project_uuid")
    return True


def project_uuid(project: Path) -> str:
    """Stable shared UUID naming the project (not the checkout)."""
    layout = read_layout(project)
    value = layout.get("project_uuid") if isinstance(layout, dict) else None
    if not isinstance(value, str) or not value:
        raise ValidationError("No versioned DADO layout with a project UUID; run `dado init`")
    return value


def checkout_uuid(project: Path) -> str:
    """Stable per-checkout UUID from the ignored local identity file."""
    value = read_yaml(identity_path(project))
    if isinstance(value, dict) and isinstance(value.get("checkout_uuid"), str) and value["checkout_uuid"]:
        return value["checkout_uuid"]
    fresh = {"checkout_uuid": str(uuid.uuid4())}
    path = identity_path(project)
    path.parent.mkdir(parents=True, exist_ok=True)
    atomic_write(path, yaml.safe_dump(fresh, sort_keys=False, allow_unicode=True))
    return fresh["checkout_uuid"]


def new_work_uuid() -> str:
    return str(uuid.uuid4())


def new_execution_uuid() -> str:
    return str(uuid.uuid4())


# ------------------------------------------------------------ git truth

def tracked_operational_files(project: Path) -> dict[str, list[str]]:
    """Inventory which DADO/OpenCode operational files git tracks.

    Paths are relative to ``project`` (e.g. ``.dado/config.yaml``,
    ``.opencode/agents/dado-master.md``). Nothing is modified; the splits are:

    - ``tracked_shared_work`` — ``.dado/work/project/**`` only (committed on
      purpose via explicit promotion);
    - ``tracked_operational`` — every other tracked ``.dado`` path (runtime
      state such as ``local/``, ``work/active|archive|imports|events|index``,
      ``backups/``, ``.txn/``, locks, generated files);
    - ``tracked_local_files`` — the subset that must stay checkout-local
      under ADR 0005.
    """
    project = Path(project).resolve()
    try:
        raw = subprocess.run(
            ["git", "ls-files", "-z", "--", LAYOUT_DIR, ".opencode"],
            cwd=project, capture_output=True, timeout=30, check=True,
        ).stdout
        tracked = [line for line in raw.decode("utf-8").split("\0") if line]
    except (OSError, subprocess.SubprocessError) as exc:
        # Not a repository or no git available: report the fact, never guess.
        return {
            "tracked_dado": [],
            "tracked_opencode": [],
            "tracked_role_agents": [],
            "tracked_shared_work": [],
            "tracked_operational": [],
            "tracked_local_files": [],
            "note": f"git ls-files unavailable: {type(exc).__name__}",
        }
    dados = sorted(entry for entry in tracked if entry.startswith(f"{LAYOUT_DIR}/"))
    opencode = sorted(entry for entry in tracked if entry.startswith(".opencode/"))
    role_agents = sorted(
        Path(entry).name.removesuffix(".md") for entry in opencode
        if Path(entry).parent.as_posix() == ".opencode/agents" and Path(entry).name.startswith("dado-")
    )
    shared_work: list[str] = []
    operational: list[str] = []
    for entry in dados:
        rel = entry[len(f"{LAYOUT_DIR}/"):]
        if rel == SHARED_WORK_PREFIX or rel.startswith(f"{SHARED_WORK_PREFIX}/"):
            shared_work.append(entry)
        else:
            operational.append(entry)
    local = sorted(
        entry for entry, rel in ((e, e[len(f"{LAYOUT_DIR}/"):]) for e in operational)
        if _dado_relpath_is_local(rel)
    )
    return {
        "tracked_dado": dados,
        "tracked_opencode": opencode,
        "tracked_role_agents": role_agents,
        "tracked_shared_work": shared_work,
        "tracked_operational": operational,
        "tracked_local_files": local,
        "note": "tracked by git; DADO never removes or rewrites tracked content",
    }


def _dado_relpath_is_local(rel: str) -> bool:
    """True when a ``.dado``-relative path is checkout-local under ADR 0005."""
    if rel in {LOCAL_CONFIG_NAME, IDENTITY_NAME, MANIFEST_NAME}:
        return True
    if rel.startswith(("local/", ".txn/", "backups/", "work/imports/")):
        return True
    if rel in {"work/events.jsonl", "work/index.yaml"}:
        return True
    if rel.startswith(("work/active/", "work/archive/")):
        return True
    return rel.endswith(".lock")


def tracked_roles(project: Path, roles: list[str] | tuple[str, ...]) -> list[str]:
    """Which of ``roles`` have git-tracked agent files."""
    inventory = tracked_operational_files(project)
    tracked = set(inventory["tracked_opencode"])
    return [role for role in roles if f".opencode/agents/{role}.md" in tracked]


# ------------------------------------------------------- .dado/.gitignore

def ensure_gitignore(project: Path) -> bool:
    """Extend ``.dado/.gitignore`` with required local entries, safely.

    Never removes or reorders existing lines, never touches tracked content,
    never deletes files. Returns True when the file changed.
    """
    path = gitignore_path(project)
    existing = ""
    if path.exists():
        try:
            existing = path.read_text(encoding="utf-8")
        except OSError as exc:
            raise ConflictError(f"Cannot read DADO gitignore {path}: {exc}") from exc
    present = {line.strip() for line in existing.splitlines()}
    missing = [entry for entry in GITIGNORE_ENTRIES if entry not in present]
    if not missing:
        return False
    content = existing.rstrip("\n")
    if content:
        content += "\n\n"
    if GITIGNORE_HEADER not in present:  # keep a single generated header
        content += GITIGNORE_HEADER + "\n"
    content += "\n".join(missing) + "\n"
    atomic_write(path, content)
    return True


# ------------------------------------------------------------ config split

def _reject_unknown_keys(config: dict[str, Any], context: str) -> None:
    unknown = sorted(key for key in config if key not in set(POLICY_KEYS) | set(PROFILE_KEYS))
    if unknown:
        raise ValidationError(f"Unknown DADO config key(s) in {context}: {', '.join(unknown)}")


def _reject_local_policies(config: dict[str, Any], context: str) -> None:
    policies = sorted(key for key in config if key in POLICY_KEYS)
    if policies:
        raise ValidationError(
            f"Policy key(s) rejected in local config {context}: {', '.join(policies)}. "
            f"Policies are shared and live only in {SHARED_CONFIG_NAME}; "
            "a checkout cannot relax them locally."
        )


def _reject_shared_profiles(config: dict[str, Any], context: str) -> None:
    profiles = sorted(key for key in config if key in PROFILE_KEYS)
    if profiles:
        raise ValidationError(
            f"Profile key(s) rejected in shared config {context}: {', '.join(profiles)}. "
            f"Model profiles are local and live in {LOCAL_CONFIG_NAME}."
        )


def _check_profile_pairing(config: dict[str, Any], context: str) -> None:
    if ("profiles" in config) != ("active_profile" in config):
        raise ValidationError(f"{context} must define profiles and active_profile together")
    if "profiles" in config:
        if not isinstance(config["profiles"], dict):
            raise ValidationError(f"profiles must be a mapping in {context}")
        if not isinstance(config["active_profile"], str):
            raise ValidationError(f"active_profile must be a string in {context}")


def _read_config(path: Path, context: str, *, required: bool) -> dict[str, Any]:
    if not path.exists():
        if required:
            raise ValidationError(f"{context} is missing; run `dado init`")
        return {}
    value = read_yaml(path)
    if not isinstance(value, dict):
        raise ValidationError(f"{context} must contain a mapping; run `dado init`")
    return value


def load_effective_config(project: Path, *, bootstrap: bool = False) -> dict[str, Any]:
    """Merged configuration view for Store integration.

    Layout2: shared policies from ``config.yaml`` plus profile state from
    ``config.local.yaml`` — with the invariant that local files can never hold
    policy keys, so a checkout cannot relax shared policies. Legacy: the full
    ``config.yaml``, identical to previous behavior.

    The shared half is required for initialized v2 read-throughs: a missing
    shared config must never silently relax default policies. Pass
    ``bootstrap=True`` only for the explicit seeding path (fresh layout init
    where ``Store`` wiring writes the policies next).
    """
    if not is_layout2(project):
        return _read_config(shared_config_path(project), f"{SHARED_CONFIG_NAME}", required=True)
    shared = _read_config(
        shared_config_path(project), f"Shared {SHARED_CONFIG_NAME}",
        required=not bootstrap,
    )
    _reject_unknown_keys(shared, SHARED_CONFIG_NAME)
    _reject_shared_profiles(shared, SHARED_CONFIG_NAME)  # profile state moved local
    local = _read_config(config_path_for_profiles(project), LOCAL_CONFIG_NAME, required=True)
    _reject_unknown_keys(local, LOCAL_CONFIG_NAME)
    _reject_local_policies(local, LOCAL_CONFIG_NAME)
    _check_profile_pairing(local, LOCAL_CONFIG_NAME)
    effective = {key: value for key, value in shared.items() if key in POLICY_KEYS}
    effective.update(local)
    return effective


def write_effective_config(project: Path, config: dict[str, Any]) -> dict[str, Path]:
    """Split a full config into shared and local halves and write both.

    Layout2 writes policy keys into ``config.yaml`` and profile keys into
    ``config.local.yaml``, always through the durable journal — no silent
    atomic fallback when the transactions module is unavailable. This
    function never serializes callers itself: the caller owns any needed
    lock (e.g. the ``.model-profiles`` lock, like :meth:`models.migrate`).
    Returns half → path mapping.
    """
    if not isinstance(config, dict):
        raise ValidationError("DADO config must be a mapping")
    if not is_layout2(project):
        path = shared_config_path(project)
        path.parent.mkdir(parents=True, exist_ok=True)
        atomic_write(path, yaml.safe_dump(config, sort_keys=False, allow_unicode=True, width=100))
        return {SHARED_CONFIG_NAME: path}
    _reject_unknown_keys(config, "effective config")
    shared_half = {key: config[key] for key in POLICY_KEYS if key in config}
    local_half = {key: config[key] for key in PROFILE_KEYS if key in config}
    _check_profile_pairing(local_half, LOCAL_CONFIG_NAME)
    shared_path, local_path = shared_config_path(project), local_config_path(project)
    shared_text = yaml.safe_dump(shared_half, sort_keys=False, allow_unicode=True, width=100)
    local_text = yaml.safe_dump(local_half, sort_keys=False, allow_unicode=True, width=100)
    if FileTransaction is None:
        raise ConflictError("Durable transaction journal unavailable; refusing unsafe layout writes")
    tx = FileTransaction.begin(dado_dir(project), roots=[dado_dir(project)], label="layout-write-config")
    tx.write(shared_path, shared_text)
    tx.write(local_path, local_text)
    tx.apply()
    return {SHARED_CONFIG_NAME: shared_path, LOCAL_CONFIG_NAME: local_path}


# --------------------------------------------------------------------- init

def initialize_layout(project: Path) -> dict[str, Any]:
    """Create the versioned layout marker, checkout identity and gitignore.

    Refuses legacy projects that still carry profiles in the shared config:
    those must run :func:`migrate` first so profile extraction lands
    atomically with the marker instead of in two divergent steps.
    """
    project = Path(project)
    if is_layout2(project):  # strict: malformed/unknown markers raise here
        return read_layout(project)  # validated mapping by the strict gate
    legacy = read_yaml(shared_config_path(project))
    if isinstance(legacy, dict) and (set(legacy) & set(PROFILE_KEYS)):
        raise ConflictError(
            f"{SHARED_CONFIG_NAME} still holds model profiles; run the layout migration "
            "(`dado migrate --apply`) to move them into config.local.yaml before initializing layout 2"
        )
    layout = {
        "version": LAYOUT_VERSION,
        "project_uuid": str(uuid.uuid4()),
        "created_at": _ts(),
    }
    layout_path(project).parent.mkdir(parents=True, exist_ok=True)
    with file_lock(project / LAYOUT_DIR / ".model-profiles", timeout=LOCK_TIMEOUT):
        if is_layout2(project):  # initialized concurrently meanwhile; first writer wins
            layout = read_layout(project)
        else:
            atomic_write(layout_path(project), yaml.safe_dump(layout, sort_keys=False, allow_unicode=True))
    ensure_gitignore(project)
    checkout_uuid(project)
    return layout


# ---------------------------------------------------------------- migration

def legacy_config_bytes(project: Path) -> bytes | None:
    path = shared_config_path(project)
    if not path.exists():
        return None
    return path.read_bytes()


def _backup_legacy(dado: Path, raw: bytes) -> tuple[Path, Path]:
    target_dir = dado / BACKUP_ROOT / f"{_stamp()}-{_sha256(raw)[:12]}"
    config_copy = target_dir / SHARED_CONFIG_NAME
    config_copy.parent.mkdir(parents=True, exist_ok=True)
    atomic_write(config_copy, raw.decode("utf-8"))
    manifest = target_dir / "manifest.json"
    record = {
        "source": str(dado / SHARED_CONFIG_NAME),
        "source_sha256": _sha256(raw),
        "backed_up_sha256": _sha256(config_copy.read_bytes()),
        "at": _ts(),
    }
    atomic_write(manifest, json.dumps(record, indent=2, sort_keys=True) + "\n")
    return config_copy, manifest


def migrate(project: Path, *, apply: bool = False, dry_run: bool | None = None) -> dict[str, Any]:
    """Migrate a legacy single-config project to the shared/local split.

    Dry-run (``dry_run=True`` or default) inventories the tracked-file state,
    previews backups and the extraction, and changes nothing. ``apply=True``
    backs up the legacy config locally, then writes the policies-only shared
    config, the local profile config and the ``version: 2`` layout marker
    atomically — always through the transactions journal (the module is a
    hard requirement; there is no silent atomic fallback). Applied
    migrations are serialized on the ``.model-profiles`` lock (the caller of
    :func:`write_effective_config` owns that lock instead; never nest).

    Idempotent: a migrated project is reported ``already``. Guards that
    never become overwrites: git history is never rewritten, tracked files
    are never removed, and an existing divergent ``config.local.yaml`` is
    rejected untouched — the legacy extraction never clobbers user
    preferences.
    """
    if dry_run is None:
        dry_run = not apply
    if apply and dry_run:
        raise ValidationError("Pass dry_run=True for a report, or apply=True to execute, not both")
    mode = "dry-run" if dry_run else "apply"
    project = Path(project).resolve()
    dado = dado_dir(project)
    tracked = tracked_operational_files(project)
    report: dict[str, Any] = {"project": str(project), "mode": mode, "tracked": tracked}

    if is_layout2(project):  # strict: a malformed/unknown marker raises here
        if not dry_run:
            ensure_gitignore(project)
            checkout_uuid(project)
        report.update({
            "status": "already",
            "shared_policies": [],
            "extracted_profiles": [],
            "active_profile": None,
            "backup": None,
            "actions": ["layout already at version 2; nothing to migrate"],
        })
        return report

    raw = legacy_config_bytes(project)
    if raw is None:
        # Fresh project without any legacy config: layouting directly is safe.
        status = "initialized"
        actions = ["initialize layout marker, checkout identity and .dado/.gitignore"]
        if dry_run:
            status = f"dry-run:{status}"
        else:
            initialize_layout(project)
        report.update({
            "status": status,
            "shared_policies": [],
            "extracted_profiles": [],
            "active_profile": None,
            "backup": None,
            "backup_manifest": None,
            "actions": actions,
        })
        return report

    try:
        legacy = yaml.safe_load(raw.decode("utf-8"))
    except (yaml.YAMLError, UnicodeDecodeError) as exc:
        raise ConflictError(f"Legacy DADO config is not valid YAML: {exc}") from exc
    if not isinstance(legacy, dict):
        raise ConflictError("Legacy DADO config must contain a mapping")
    _reject_unknown_keys(legacy, f"legacy {SHARED_CONFIG_NAME}")
    policy_half = {key: legacy[key] for key in POLICY_KEYS if key in legacy}
    profile_half = {key: legacy[key] for key in PROFILE_KEYS if key in legacy}
    profiles = profile_half.get("profiles")
    if not isinstance(profiles, dict) or not profiles:
        raise ConflictError(
            f"Legacy {SHARED_CONFIG_NAME} has no model profiles to extract; "
            "nothing to migrate (run `dado init` instead)"
        )
    _check_profile_pairing(profile_half, f"legacy {SHARED_CONFIG_NAME}")

    if f"{LAYOUT_DIR}/{LOCAL_CONFIG_NAME}" in tracked["tracked_local_files"] and not dry_run:
        raise ConflictError(
            f".dado/{LOCAL_CONFIG_NAME} is tracked by git; DADO refuses to write through tracked files. "
            f"Remove it from the index first with `git rm --cached .dado/{LOCAL_CONFIG_NAME}`."
        )

    # Guard: existing (untracked) local profile state is user preference —
    # never silently overwritten by the extraction.
    local_divergence = False
    local_path = local_config_path(project)
    profile_text = yaml.safe_dump(profile_half, sort_keys=False, allow_unicode=True, width=100)
    if local_path.exists():
        try:
            existing_local_text = local_path.read_text(encoding="utf-8")
        except OSError as exc:
            raise ConflictError(f"Cannot read existing local config {local_path}: {exc}") from exc
        local_divergence = existing_local_text != profile_text

    backup_target = f"dado/{BACKUP_ROOT}/{_stamp()}-{_sha256(raw)[:12]}/"
    actions = [
        f"back up legacy {SHARED_CONFIG_NAME} to .dado/{BACKUP_ROOT}/",
        f"write policies-only {SHARED_CONFIG_NAME}",
        f"write local {LOCAL_CONFIG_NAME} with profiles and active_profile",
        f"write version {LAYOUT_VERSION} layout marker {LAYOUT_FILENAME}",
    ]
    if dry_run:
        report.update({
            "status": "dry-run",
            "shared_policies": sorted(policy_half),
            "extracted_profiles": sorted(profiles),
            "active_profile": profile_half.get("active_profile"),
            "backup_preview": backup_target,
            "actions": actions,
            "local_state_divergent": local_divergence,
            "tracked_follow_up": [
                (f"{entry} is tracked; commit this shared-side change yourself"
                 if entry in (f"{LAYOUT_DIR}/{SHARED_CONFIG_NAME}", f"{LAYOUT_DIR}/{LAYOUT_FILENAME}")
                 else f"{entry} stays tracked (reported, not touched)")
                for entry in tracked["tracked_operational"]
            ],
        })
        return report

    if local_divergence:
        raise ConflictError(
            f"{LOCAL_CONFIG_NAME} already holds divergent local profile state; the legacy "
            "extraction refuses to overwrite user preferences. Review "
            f"{local_path}, reconcile it against the legacy config, then migrate again."
        )

    if FileTransaction is None:
        raise ConflictError("Durable transaction journal unavailable; refusing partial layout migration")

    # Serialized against profile writers on the well-known model-profiles
    # lock; nested acquisition of the same lock would deadlock, so nothing
    # inside this block may re-lock it.
    with file_lock(project / LAYOUT_DIR / ".model-profiles", timeout=LOCK_TIMEOUT):
        if not dado.exists():
            dado.mkdir(parents=True, exist_ok=True)
        backup_config, backup_manifest = _backup_legacy(dado, raw)
        layout = {"version": LAYOUT_VERSION, "project_uuid": str(uuid.uuid4()), "created_at": _ts()}
        shared_text = yaml.safe_dump(policy_half, sort_keys=False, allow_unicode=True, width=100)
        layout_text = yaml.safe_dump(layout, sort_keys=False, allow_unicode=True)
        tx = FileTransaction.begin(dado, roots=[dado], label="layout-migration")
        tx.write(shared_config_path(project), shared_text)
        tx.write(local_path, profile_text)
        tx.write(layout_path(project), layout_text)
        tx.apply()
        ensure_gitignore(project)
        checkout_uuid(project)
    report.update({
        "status": "migrated",
        "shared_policies": sorted(policy_half),
        "extracted_profiles": sorted(profiles),
        "active_profile": profile_half.get("active_profile"),
        "backup": str(backup_config),
        "backup_manifest": str(backup_manifest),
        "actions": actions,
        "tracked_follow_up": [
            f"{entry} is tracked; commit this shared-side change yourself"
            for entry in (f"{LAYOUT_DIR}/{SHARED_CONFIG_NAME}", f"{LAYOUT_DIR}/{LAYOUT_FILENAME}")
            if entry in tracked["tracked_operational"]
        ],
    })
    return report


